#!/bin/bash
# AvailabilityFlag: Public
# CrontabFlag: True
#
# Purpose:  This script makes instance-level postgres backups as well as optional backups
#           of each individual postgres database. Additionally the script can transfer the
#           backups to a remote location specified via an SCP connect string. The script will
#           also prune old backups prior to making new backups.
#
# Naming conventions: This script will create 3 files for the instance, and 4 files for
#                     each entered database. The files will be named according to the following (missing .gz if not zipped):
#                       Object Definitions for an Instance - GLOBALOBJECTS_MM-DD-YYYY-HH-MM-SS.sql.gz               Per Instance
#                       Data for an Instance - ALLDATABASES_MM-DD-YYYY-HH-MM-SS.sql.gz                              Per Instance
#                       Sizes of the Databases on the Instance - SIZE_MM-DD-YYYY-HH-MM-SS.txt                       Per Instance and Per Database
#                       Object Definitions for an Instance (taken
#                           with each database dump) - databasename_GLOBALOBJECTS_MM-DD-YYYY-HH-MM-SS.sql.gz        Per Database
#                       Data for a Database - databasename_DATAONLY_MM-DD-YYYY-HH-MM-SS.sql.gz                      Per Database
#                       Roles and Tablespaces for a Database - databasename_ROLES_MM-DD-YYYY-HH-MM-SS.txt           Per Database
#                     PgDump.sh also writes a log, PgDump_MM-DD-YYYY-HH-MM-SS.<random>.log, to the backup directory for each dump.
#
# Notes:    The script sources ~/.bashrc, which must set PG_BACKUP_DIR (the backup directory),
#           ALL_DBA_EMAIL_LIST (the space-separated addresses that get the emails) and PGPORT, and
#           must put the PostgreSQL client tools (psql, pg_dump, pg_dumpall) on PATH.
#
#           The script appends historical backup records to $PG_BACKUP_DIR/${HOST}_backup_results.csv.
#           It writes one row per database in pg_database. Columns are hostname, instance type,
#           database name, backup start and end times, database size in bytes, backup type, and dump path.
#
#           The -p option allows you to specify the amount of processors which should be used in
#           parallel to zip the dump with -p [##] The p option is set to 4 by default if it is not
#           specified.
#
#           The script will default to sending an email containing the logs generated by a backup every
#           time the script is run. The -s option restricts this email to only be sent on Saturdays to
#           prevent excessive informational emails when the script is run on a daily basis.
#
#           The -o option overrides the PGPORT set by ~/.bashrc, to back up an instance on another port.
#           It requires -d, because each instance needs its own backup directory: the dump file names hold
#           only a timestamp, and PostgresWeeklyRestore.sh restores only the newest instance dump in a directory.
#
###################################################
usage="Usage: nohup BackupPostGreSQL.sh [ csv list of databases | NONE ] [ -s only email if saturday ] [ -t days_till_deletion (optional, default: 2) ] [ -r scp_remote_destination (optional, copy backups to specified scp destination) ] [ -n (optional, disable backup compression) ] [ -p num_processes (optional, number of processes to use during pigz compression. Default: 4) ] [ -d backup_directory (optional, sets directory to place backups. Defaults to PG_BACKUP_DIR) ] [ -o port (optional, requires -d, overrides the PGPORT set by .bashrc) ] > /tmp/BackupPostGreSQL.out 2>&1 &"
example="Example: nohup BackupPostGreSQL.sh my_db -t 2 -n > /tmp/BackupPostGreSQL.out 2>&1 &"

# Process -h option
while getopts ":h" option; do
    case $option in
    h)
        echo "$usage"
        echo "$example"
        exit 0
        ;;
    \?)
        echo "Error: the database list (or NONE) must be the first argument."
        echo "$usage"
        echo "$example"
        exit 1
        ;;
    esac
done

topt=false
nopt=false
dopt=false
sopt=false
parg=4
pgport_opt=""
OPTIND=2
# Process options that come after positional argument
while getopts ":nst:r:d:p:o:" option; do
    case $option in
    t)
        topt=true
        time_till_del=$OPTARG
        if ! [[ $time_till_del =~ ^[0-9]+$ ]]; then
            echo "ERROR: -t flag must be a number. Exiting..."
            exit 1
        fi
        if [ "$time_till_del" -gt 9 ] || [ "$time_till_del" -lt 1 ]; then
            echo "ERROR: time till deletion must be a positive number less than 10. Exiting..."
            exit 1
        fi
        ;;
    r)
        remote_loc=$OPTARG
        ;;
    s)
        sopt=true
        ;;
    n)
        nopt=true
        ;;
    d)
        dopt=true
        backup_dir="$OPTARG"
        ;;
    p)
        parg="$OPTARG"
        ;;
    o)
        pgport_opt="$OPTARG"
        if ! [[ "$pgport_opt" =~ ^[0-9]+$ ]]; then
            echo "ERROR: -o flag must be a port number, got $OPTARG. Exiting..."
            exit 1
        fi
        ;;
    :)
        echo "Error: -$OPTARG requires an argument"
        echo "$usage"
        echo "$example"
        exit 1
        ;;
    \?)
        echo "Error: Invalid option"
        echo "$usage"
        echo "$example"
        exit 1
        ;;
    esac
done

# Check args: getopts stops at the first argument that is not an option, so every argument
# after the database list was parsed only if OPTIND moved past the last one
if [ $# -lt 1 ] || [ $# -ne $((OPTIND-1)) ]; then
    echo "Error invalid arguments to BackupPostGreSQL.sh"
    echo "$usage"
    echo "$example"
    exit 1
fi

# Each instance needs its own backup directory (see the -o note in the header).
if [ -n "$pgport_opt" ] && ! $dopt; then
    echo "ERROR: -o requires -d, so the other instance's backups go to their own directory. Exiting..."
    echo "$usage"
    echo "$example"
    exit 1
fi

# Set env variables
# Sourced before validating arguments so $ALL_DBA_EMAIL_LIST is set for the error emails below
# $ALL_DBA_EMAIL_LIST is deliberately unquoted in every mailx call: s-nail (mailx on RHEL 9) takes
# one address per argument and rejects an argument holding several. Unquoted, a space-separated list
# splits into one argument per address, which needs IFS to contain a space at every mailx call, so
# comma lists below are split with a scoped 'IFS=, read' rather than by changing IFS globally.
source "$HOME/.bashrc"
if [ $? -ne 0 ]; then
    echo "An error occurred while sourcing $HOME/.bashrc. Exiting..."
    exit 1
fi
# Source the logging library to use its functions
source "$HOME/common/general/Logging.sh"
if [ $? -ne 0 ]; then
    echo "An error occurred while sourcing the logging library. Exiting..."
    exit 1
fi
timestamp="$(date +"%Y-%m-%d_%H_%M_%S")"
if ! log_file=$(mktemp "/tmp/BackupPostGreSQL-${timestamp}.XXXXX.log"); then
    echo "An error occurred while creating the log file. Exiting..."
    exit 1
fi

set_general_logging "$log_file"
if [ $? -ne 0 ]; then
    echo "An error occurred while setting general logging for $log_file. Exiting..."
    echo "An error occurred while setting general logging for $log_file. Exiting..." | mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed due to set general logging" $ALL_DBA_EMAIL_LIST
    exit 1
fi
echo "Log location: $log_file"

# Ensure processor arg is a number greater than 0
if ! [[ "$parg" =~ ^[0-9]+$ ]]; then
    echo "Error: Processor argument (the arg following the -p flag) must be a number"
    # Close the log before reading from it to prevent race conditions
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed due to invalid processor argument" $ALL_DBA_EMAIL_LIST <"$log_file"
    exit 1
elif [ "$parg" -le 0 ]; then
    echo "Error: Number in processor argument (following -p flag) must be greater than 0"
    # Close the log before reading from it to prevent race conditions
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed due to invalid processor argument" $ALL_DBA_EMAIL_LIST <"$log_file"
    exit 1
fi

# Set user parameters to variables
databases=${1,,}

if [ -n "$pgport_opt" ]; then
    export PGPORT="$pgport_opt"
fi

# Check that instance is running.
instance_check=$("$HOME/common/postgres/CheckInstanceOpenStatus.sh")
if [ $? -ne 0 ]; then
    echo "$instance_check"
    echo "Error occurred while checking open status of instance on port $PGPORT."
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed checking instance open status" $ALL_DBA_EMAIL_LIST < "$log_file"
    exit 1
elif [ "$instance_check" != "open" ]; then
    echo "No instance open on port $PGPORT"
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed because instance was not open" $ALL_DBA_EMAIL_LIST < "$log_file"
    exit 1
fi

HOST=$(hostname)

# Timestamp used when appending to summary CSV.
datevar=$(date +%m-%d-%Y-%H-%M-%S)
# User-facing timestamp for reporting start time and duration of script.
pre_dump_timestamp=$(date "+%Y-%m-%d %H:%M:%S")
echo
echo "BackupPostGreSQL starting at $pre_dump_timestamp"
echo
# Day of the week (1 = Monday ... 7 = Sunday), used by the -s option to only email on Saturday
dayOfWeek=$(date '+%u')
# Set to 1 by non-fatal errors so the final email subject can indicate an error
exit_status=0

# Set PG_BACKUP_DIR to -d argument if provided
if $dopt; then
    export PG_BACKUP_DIR="$backup_dir"
fi

# Check that inputted backup directory exists
if [ -z "$PG_BACKUP_DIR" ]; then
    echo "Error: backup directory \$PG_BACKUP_DIR not set. Exiting..."
    # Close the log before reading from it to prevent race conditions
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed because backup directory is not set" $ALL_DBA_EMAIL_LIST <"$log_file"
    exit 1
elif [ ! -d "$PG_BACKUP_DIR" ]; then
    # Create a new backup directory at the given location if it is not found
    echo "Backup directory $PG_BACKUP_DIR does not exist."
    echo "Creating directory $PG_BACKUP_DIR"
    mkdir -p "$PG_BACKUP_DIR"
    if [ $? -ne 0 ]; then
        echo "Error occurred while creating backup directory $PG_BACKUP_DIR. Exiting..."
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed creating backup directory" $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi
fi
# Make the path absolute: the script cds into it below, after which a relative path would point elsewhere.
if ! PG_BACKUP_DIR=$(cd "$PG_BACKUP_DIR" && pwd); then
    echo "Error occurred while resolving the backup directory to an absolute path. Exiting..."
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed resolving backup directory" $ALL_DBA_EMAIL_LIST <"$log_file"
    exit 1
fi

result_file=$PG_BACKUP_DIR/${HOST}_backup_results.csv

# Finding previous instance level backup files to be used in estimating the size of the backup
# These may or may not exist in the given backup directory; size estimate will only be made if found
if $nopt; then
    # Set old_files variable by checking UNZIPPED backup files for size estimate
    old_files="$(find -L "$PG_BACKUP_DIR" -name "ALLDATA*.sql" | head -1),$(find -L "$PG_BACKUP_DIR" -name "*GLOBALOBJECTS*.sql" | head -1)"
    zipped_status="UNZIPPED"
else
    # Set old_files variable by checking ZIPPED backup files for size estimate
    old_files="$(find -L "$PG_BACKUP_DIR" -name "ALLDATA*.sql.gz" | head -1),$(find -L "$PG_BACKUP_DIR" -name "*GLOBALOBJECTS*.sql.gz" | head -1)"
    zipped_status="ZIPPED"
fi

# Variable to keep track of which databases entered don't have backup files already associated.
# This will be used at the end to warn the user if certain databases are not included in the size estimate.
no_files_exist=""
# Split the comma-separated database list into an array. IFS=',' applies to this read only, so the
# global IFS stays at its default and $ALL_DBA_EMAIL_LIST still splits on spaces in the mailx calls below.
IFS=',' read -r -a database_list <<< "$databases"
for db in "${database_list[@]}"; do
    # Case for no individual databases to be backed up
    if [ "${db^^}" = "NONE" ]; then
        break
    fi

    # Finding the database level backup file name (only need the first one if more than one exists
    # as only new backup file will be created)
    db_files="$(find -L "$PG_BACKUP_DIR" -name "${db}_DATAONLY*.sql*" | head -1)"

    # Setting the variable that holds the instance level backup file names to also hold the database level backup file names
    old_files="$old_files,$db_files"

    # If no files were found, keep track of that in the no_files_exist variable.
    if [ -z "${db_files}" ]; then
        no_files_exist="$no_files_exist, $db"
    fi
done

# Remove leading commas from the variable to keep track of databases with no present files.
no_files_exist=$(echo "$no_files_exist" | sed "s/^, //")

# Initializing the variable to keep track of the size of all previously stored filenames
size=0

# Loop through each found file and add the size to the total size counter.
# Split the comma-separated file list into an array; IFS=',' applies to this read only.
IFS=',' read -r -a old_file_list <<< "$old_files"
for file in "${old_file_list[@]}"; do
    if [ -n "$file" ]; then
        # Finding size of old file. awk prints the size portion of the output. sed removes the suffix for the size.
        file_size=$(ls -l --block-size=KiB "$file" | awk '{print $5}' | sed 's/KiB//')
        if [[ "$file_size" =~ ^[0-9]+$ ]]; then
            size=$((size + file_size))
        fi
    fi
done

# Output results of size estimate
if [ $size -ne 0 ]; then
    echo "Estimated size of $zipped_status backup files: ${size}KiB"
else
    echo "Unable to provide file size estimate. No previous $zipped_status backup files found in backup directory. Continuing..."
fi

# Case for some databases entered which had no backup files to be found. Output warning to user.
if [ -n "$no_files_exist" ] && [ "${db^^}" != "NONE" ]; then
    echo "Warning: no backup files found for databases $no_files_exist. Size of these databases not included in estimation."
fi

# If the time isn't given to delete the old backup files, set to default 2 days.
if ! $topt; then
    time_till_del=2
fi
# Old PgDump logs, SIZE files and ROLES files are pruned on every run, since PgDump.sh writes them before
# dumping and a failed run leaves them without a dump. Old dumps are pruned only when previous backup files
# were found above.
prune_patterns=("PgDump_*.log" "SIZE*.txt*" "*_ROLES_*.txt")
if [ $size -ne 0 ]; then
    echo "Removing backups that are older than $time_till_del days old..."
    # ALLDATA* matches both the old ALLDATA and current ALLDATABASES filenames.
    prune_patterns+=("ALLDATA*.sql*" "*GLOBALOBJECTS*.sql*" "*DATAONLY*.sql*")
fi
for pattern in "${prune_patterns[@]}"; do
    res=$("$HOME/common/general/RemoveOldFiles.sh" "$PG_BACKUP_DIR" "$pattern" "$time_till_del")
    if [ $? -ne 0 ]; then
        echo "$res"
        echo "Error removing old backups..."
        echo "Call to script '$HOME/common/general/RemoveOldFiles.sh $PG_BACKUP_DIR \"$pattern\" $time_till_del' failed"
        echo "Exiting..."
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed removing old backups" $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi
done

# Changing into the backup directory since it has been verified to exist.
# All scripts are run using their full path, so no need to remain in the common/postgres
# directory. According to shellcheck this is correct syntax for catching a failed cd command.
cd "$PG_BACKUP_DIR" || {
    echo "Error changing into backup directory $PG_BACKUP_DIR. Exiting..."
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed changing into backup directory" $ALL_DBA_EMAIL_LIST <"$log_file"
    exit 1
}

# Check whether any databases were inputted
if [ "${databases^^}" == "NONE" ]; then
    databases=""
fi

# Split the comma-separated database list into an array for the existence check and the dumps below.
# IFS=',' applies to this read only, so the global IFS is never left at ',' for the mailx calls.
IFS=',' read -r -a database_list <<< "$databases"
# Check that the entered databases exist
if [ -n "$databases" ]; then
    echo "Checking if databases exist..."
    for database in "${database_list[@]}"; do
        db_exists=$("$HOME/common/postgres/CheckIfDatabaseExists.sh" "$database")

        if [ $? -ne 0 ]; then
            echo "Error occurred while checking $database database for existence. Exiting..."
            echo "$db_exists"
            # Close the log before reading from it to prevent race conditions
            close_logs
            mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed checking database $database" $ALL_DBA_EMAIL_LIST <"$log_file"
            exit 1
        elif [ "$db_exists" != "Yes" ]; then
            echo "$database database does not exist. Exiting..."
            # Close the log before reading from it to prevent race conditions
            close_logs
            mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed checking database $database" $ALL_DBA_EMAIL_LIST <"$log_file"
            exit 1
        fi
    done

    echo "Databases checked successfully. Continuing..."
    echo

    # Check that the backup directory size is large enough
    backup_dir_size=$(du -s "$PG_BACKUP_DIR" | xargs | awk '{print $1}')
    backup_dir_available=$(df "$PG_BACKUP_DIR" | tail -1 | xargs | awk '{print $4}')

    # Calculate the required space as 210% of the current backup directory size
    # using the bash calculator bc
    required_space=$(echo "$backup_dir_size * 2.1" | bc)

    # Check if the directory size has been exceeded
    if (($(echo "$backup_dir_available < $required_space" | bc))); then
        echo "$PG_BACKUP_DIR directory is not large enough for the backup files. Location must be 110% larger."
        echo "Room in backup directory: $backup_dir_available KB"

        # Display required space without decimal by cutting off remainder using cut command
        echo "Required space: $(echo "$required_space" | cut -d "." -f1) KB"
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed due to space concerns." $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi
    echo "Databases exist. Continuing..."
fi

if [ -n "$remote_loc" ]; then
    # Test the connection to the remote location
    # If the connection asks for a password, the oBatchMode=yes setting causes
    # the connection to close rather than hanging and waiting for a password entry
    remote_loc_minus_directory=$(echo "$remote_loc" | sed 's/:.*$//g')
    remote_loc_directory=$(echo "$remote_loc" | sed 's/^.*://g')
    valid_connect=$(ssh -oBatchMode=yes "$remote_loc_minus_directory")
    if [ $? -ne 0 ]; then
        echo "Error: unable to connect to $remote_loc_minus_directory destination. Exiting..."
        echo "$valid_connect"
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed checking remote connection" $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi

    valid_folder=$(ssh -oBatchMode=yes "$remote_loc_minus_directory" "[ -d $remote_loc_directory ]")
    if [ $? -ne 0 ]; then
        echo "Error: unable to connect to $remote_loc_minus_directory destination. Exiting..."
        echo "$valid_folder"
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed checking remote connection" $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi

    echo "Remote location validated"
    echo
fi

# Size check will be skipped if no previous backups in directory are found to use for size estimation
if [ -n "$size" ]; then
    backup_dir_available=$(df "$PG_BACKUP_DIR" | tail -1 | xargs | awk '{print $4}')

    # Calculate the required space as 210% of the most recent backup size using bash calculator (bc)
    required_space=$(echo "$size * 2.1" | bc)

    # Check if the directory size will be exceeded by the backup
    if (($(echo "$backup_dir_available < $required_space" | bc))); then
        echo "Error: $PG_BACKUP_DIR directory is not large enough for the backup files."
        echo "Room in backup directory: $backup_dir_available KB"

        # Display required space without decimal by cutting off remainder using cut command
        echo "Required space: $(echo "$required_space" | cut -d "." -f1) KB"
        echo "Exiting..."
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed due to space concerns." $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi
fi

echo "Dumping entire instance to $PG_BACKUP_DIR..."

# Print start timestamp for instance dump
pre_instance_dump_timestamp=$(date "+%Y-%m-%d %H:%M:%S")
echo "Dumping entire instance starting at time: $pre_instance_dump_timestamp"

# Backup instance as a whole
# This call creates the ALLDATABASES_DATESTAMP and GLOBALOBJECTS_DATESTAMP files.
if $nopt; then
    # No zip
    dump_results=$("$HOME/common/postgres/PgDump.sh" "-n" "-p" "$parg" "ALL")
else
    # Zipped
    dump_results=$("$HOME/common/postgres/PgDump.sh" "-p" "$parg" "ALL")
fi
if [ $? -ne 0 ]; then
    echo "Error making the instance backup:"
    echo "$dump_results"
    echo "Exiting..."
    # Close the log before reading from it to prevent race conditions
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed making instance backup" $ALL_DBA_EMAIL_LIST <"$log_file"
    exit 1
fi

# Print end timestamp for instance dump and time elapsed
post_instance_dump_timestamp=$(date "+%Y-%m-%d %H:%M:%S")
echo "Dumping entire instance finished at time: $post_instance_dump_timestamp"

# Print time elapsed for dumping individual database
instance_complete_time=$("$HOME/common/general/ComputeTimeGap.sh" "$pre_instance_dump_timestamp" "$post_instance_dump_timestamp")
if [ $? -ne 0 ]; then
    echo "Error occurred while attempting to compute elapsed time for dump of instance. Continuing..."
else
    echo "Total time elapsed for dumping instance was: $instance_complete_time"
fi
echo


echo "Dumping individual databases to $PG_BACKUP_DIR..."
echo
# Dump individual databases to standalone file
# Creates the files DB_DATAONLY_DATESTAMP
for database in "${database_list[@]}"; do
    # Print start timestamp for individual database dump
    pre_db_dump_timestamp=$(date "+%Y-%m-%d %H:%M:%S")
    echo "Dumping database $database starting at time: $pre_db_dump_timestamp"

    if $nopt; then
        # No zip
        database_dump_results=$("$HOME/common/postgres/PgDump.sh" "-n" "-p" "$parg" "DATA" "$database")
    else
        # Zipped
        database_dump_results=$("$HOME/common/postgres/PgDump.sh" "-p" "$parg" "DATA" "$database")
    fi

    if [ $? -ne 0 ]; then
        echo "Error making the $database database backup:"
        echo "$database_dump_results"
        echo "Exiting..."
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed making $database backup" $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi

    # Print end timestamp for individual database dump and time elapsed
    post_db_dump_timestamp=$(date "+%Y-%m-%d %H:%M:%S")
    echo "Dumping database $database finished at time: $post_db_dump_timestamp"

    # Print time elapsed for dumping individual database
    db_complete_time=$("$HOME/common/general/ComputeTimeGap.sh" "$pre_db_dump_timestamp" "$post_db_dump_timestamp")
    if [ $? -ne 0 ]; then
        echo "Error occurred while attempting to compute elapsed time for dump of database $database. Continuing..."
    else
        echo "Total time for dumping database $database was: $db_complete_time"
    fi
    echo
done

# End timestamp for the summary CSV.
date_end=$(date +%m-%d-%Y-%H-%M-%S)
# End timestamp for user-facing output and computing script duration.
post_dump_timestamp=$(date "+%Y-%m-%d %H:%M:%S")
echo
echo "BackupPostGreSQL finished at $post_dump_timestamp"

complete_time=$("$HOME/common/general/ComputeTimeGap.sh" "$pre_dump_timestamp" "$post_dump_timestamp")
if [ $? -ne 0 ]; then
    echo "Error occurred while attempting to compute elapsed time for full dump."
else
    echo "Total time for BackupPostGreSQL was: $complete_time"
fi
echo
echo "Databases dumped successfully"

echo "Creating csv file for historical database size tracking..."
csv_failed=0

# The instance dump's SIZE file holds one "database,bytes" line per database, then an "all,<total bytes>"
# line. PgDump.sh names the file in its output.
size_file=$(printf '%s\n' "$dump_results" | sed -nE 's/^Outputting sizes to (.+)$/\1/p')
if [ -z "$size_file" ] || [ ! -f "$size_file" ]; then
    echo "Unable to find the SIZE file written by the instance dump. Skipping historical CSV records."
    csv_failed=1
else
    # sed '$d' drops the last line, the instance total, which is not a database.
    database_sizes=$(sed '$d' "$size_file")
    if [ -z "$database_sizes" ]; then
        echo "SIZE file $size_file lists no databases. Skipping historical CSV records."
        csv_failed=1
    fi
fi

# Use the output from the instance dump to determine the filename of the ALLDATABASES dump file for the historical CSV file.
instance_dump_name=$(printf '%s\n' "$dump_results" | sed -nE 's/^Dump of postgres to (ALLDATABASES_[0-9-]+\.sql(\.gz)?) was successful$/\1/p')
instance_dump_file="$PWD/$instance_dump_name"
if [ -z "$instance_dump_name" ] || [ ! -f "$instance_dump_file" ]; then
    echo "WARNING: Unable to identify the instance dump created by PgDump.sh. Continuing..."
    instance_dump_file="UNKNOWN"
fi

# If we didn't encounter errors up to this point, start writing entries to CSV file.
if [ $csv_failed -eq 0 ]; then
    while read -r line; do
        IFS=, read -r database database_size extra <<< "$line"
        if [ -z "$database" ] || ! [[ "$database_size" =~ ^[0-9]+$ ]] || [ -n "$extra" ]; then
            echo "Invalid database size result. Skipping historical CSV records."
            echo "Expected entry formatted as 'database,size', got '$line'. Continuing..."
            csv_failed=1
            break
        fi
        printf '%s\n' "$HOST,postgres,$database,${datevar},${date_end},$database_size,FULL,$instance_dump_file" >> "$result_file"
        if [ $? -ne 0 ]; then
            echo "An error occurred while writing size record to CSV file. Continuing..."
            csv_failed=1
        fi
    done <<< "$database_sizes"
fi

if [ $csv_failed -ne 0 ]; then
    exit_status=1
    close_logs
    mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed creating csv file" $ALL_DBA_EMAIL_LIST <"$log_file"
    # Reopen general logging to capture the rest of the script output
    set_general_logging "$log_file"
    if [ $? -ne 0 ]; then
        # Because logging is likely broken, pipe to tee to ensure this error summary is added to log_file
        echo "An error occurred while setting general logging for $log_file. Continuing..." | tee -a "$log_file"
    fi
else
    echo "Successfully created csv file $result_file"
fi

# Copy results file and dumps to remote location if provided
if [ -n "$remote_loc" ]; then
    echo "Copying backup directory to remote location..."
    scp -pr "$PG_BACKUP_DIR" "$remote_loc"
    if [ $? -ne 0 ]; then
        echo "Error copying dumps to remote destination"
        echo "command failed: 'scp -pr $PG_BACKUP_DIR $remote_loc' "
        echo "Exiting..."
        # Close the log before reading from it to prevent race conditions
        close_logs
        mailx -s "$HOSTNAME ERROR: BackupPostGreSQL.sh failed copying dumps to remote destination" $ALL_DBA_EMAIL_LIST <"$log_file"
        exit 1
    fi
    echo "Successfully copied backups to remote destination."
fi
# Fatal errors exit before this point, so only non-fatal errors can make this an error email
if [ "$exit_status" -ne 0 ]; then
    out_logs_email_subject="Error ${HOSTNAME} PostGreSQL backups"
else
    out_logs_email_subject="Success ${HOSTNAME} PostGreSQL backups"
fi
# Close the log before reading from it to prevent race conditions
close_logs
# Send postgres backup log in an email if running on Saturday or s option is not given
if [ "$dayOfWeek" -eq 6 ] || [ "$sopt" = false ]; then
    mailx -s "$out_logs_email_subject" $ALL_DBA_EMAIL_LIST <"$log_file"
fi
exit "$exit_status"
